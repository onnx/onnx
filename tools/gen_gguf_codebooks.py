"""Generate reference and specification IQ data from pinned ggml-common.h."""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

REVISION = "da8e2a54b919557b816b1c2beb432ccb766f7ce0"
SOURCE_SHA256 = "0061131b615c5721fc88a78feeb22c1f8c450f1c2646a317d80796a653bf595c"
TABLES = {
    "iq2xxs_grid": (256, 8),
    "iq2xs_grid": (512, 8),
    "iq2s_grid": (1024, 8),
    "iq3xxs_grid": (256, 4),
    "iq3s_grid": (512, 4),
    "iq1s_grid": (2048, 8),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help=f"ggml-common.h from GGML {REVISION}")
    args = parser.parse_args()
    source = args.source.read_bytes().replace(b"\r\n", b"\n")
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("Source does not match the pinned ggml-common.h SHA256.")
    text = source.decode("utf-8")
    # REUSE-IgnoreStart
    lines = [
        "# Copyright (c) ONNX Project Contributors",
        "# Copyright (c) 2023-2026 The ggml authors",
        "#",
        "# SPDX-License-Identifier: Apache-2.0 AND MIT",
        '"""Generated by tools/gen_gguf_codebooks.py; do not edit.',
        "",
        f"GGML {REVISION}, src/ggml-common.h.",
        "IQ lookup data; the upstream MIT notice is in GGML_LICENSE.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "# name: (row width, values, bits per index, little-bit-order packed indices)",
        "CODEBOOKS: dict[str, tuple[int, tuple[int, ...], int, str]] = {",
    ]
    # REUSE-IgnoreEnd
    for name, (rows, width) in TABLES.items():
        match = re.search(
            rf"GGML_TABLE_BEGIN\(\w+, {name}, \w+\)(.*?)GGML_TABLE_END\(\)",
            text,
            re.DOTALL,
        )
        if match is None:
            raise ValueError(f"Missing table {name}")
        words = [int(value, 16) for value in re.findall(r"0x[0-9a-fA-F]+", match[1])]
        if len(words) != rows:
            raise ValueError(f"Unexpected table size for {name}: {len(words)}")
        data = b"".join(word.to_bytes(width, "little") for word in words)
        values = sorted(set(data))
        max_two_bit_values = 1 << 2
        bits = 2 if len(values) <= max_two_bit_values else 4
        indices = [values.index(value) for value in data]
        packed = bytes(
            sum(
                index << (j * bits)
                for j, index in enumerate(indices[i : i + 8 // bits])
            )
            for i in range(0, len(indices), 8 // bits)
        ).hex()
        signed_byte_limit = 1 << 7
        signed = tuple(
            value if value < signed_byte_limit else value - 256 for value in values
        )
        lines += [
            f'    "{name}": (',
            f"        {width},",
            f"        {signed!r},",
            f"        {bits},",
            "        (",
        ]
        lines += [
            f'            "{packed[i : i + 88]}"' for i in range(0, len(packed), 88)
        ]
        lines += ["        ),", "    ),"]
    lines += ["}", ""]
    output = (
        Path(__file__).resolve().parents[1]
        / "onnx"
        / "reference"
        / "ops"
        / "_gguf_codebooks.py"
    )
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    document = Path(__file__).resolve().parents[1] / "docs" / "DequantizeGGUF.md"
    text = document.read_text(encoding="utf-8")
    begin = "<!-- BEGIN GENERATED GGUF CODEBOOKS -->"
    end = "<!-- END GENERATED GGUF CODEBOOKS -->"
    if text.count(begin) != 1 or text.count(end) != 1:
        raise ValueError(
            "The decoding specification must contain one codebook section."
        )
    prefix, remainder = text.split(begin)
    _, suffix = remainder.split(end)
    table_start = next(
        i for i, line in enumerate(lines) if line.startswith("CODEBOOKS:")
    )
    tables = ["CODEBOOKS = {", *lines[table_start + 1 :]]
    document.write_text(
        prefix
        + begin
        + "\n\n```python\n"
        + "\n".join(tables)
        + "```\n\n"
        + end
        + suffix,
        encoding="utf-8",
        newline="\n",
    )


if __name__ == "__main__":
    main()
